import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NOTICE = "/* Public domain. No rights reserved. Wholly AI-authored. */\n"
GENERATED = "/* Generated by tools/gen_opengl.py from tools/data/opengl.json. */\n"
CUSTOM = {
    "glGetString",
    "glGetError",
    "glDrawBuffer",
    "glReadBuffer",
    "glRenderMode",
    "glSelectBuffer",
    "glFeedbackBuffer",
    "glVertexPointer",
    "glNormalPointer",
    "glColorPointer",
    "glIndexPointer",
    "glTexCoordPointer",
    "glEdgeFlagPointer",
    "glInterleavedArrays",
    "glEnableClientState",
    "glDisableClientState",
    "glDrawArrays",
    "glDrawElements",
    "glArrayElement",
    "glGetPointerv",
    "glPushClientAttrib",
    "glPopClientAttrib",
    "glPushAttrib",
    "glPopAttrib",
}


def element_size(kind):
    return {
        "int8_t": 1,
        "uint8_t": 1,
        "int16_t": 2,
        "uint16_t": 2,
        "int32_t": 4,
        "uint32_t": 4,
        "float": 4,
        "double": 8,
    }[kind]


def pointer_size(name, argument):
    """Lengths are component counts unless the API has a byte-oriented span."""
    match = re.fullmatch(
        r"gl(?:Color|Vertex|Normal|TexCoord|RasterPos|EvalCoord)([1-4])[a-z]+v", name
    )
    if match:
        return match[1], False
    if name.startswith("glRect"):
        return "2", False
    if name.startswith("glIndex") or name == "glEdgeFlagv":
        return "1", False
    if name in {"glLoadMatrixf", "glLoadMatrixd", "glMultMatrixf", "glMultMatrixd"}:
        return "16", False
    if name in {"glClipPlane", "glGetClipPlane"}:
        return "4", False
    if name in {"glGetBooleanv", "glGetDoublev", "glGetFloatv", "glGetIntegerv"}:
        return "gl_query_count(pname)", False
    if name in {
        "glGenTextures",
        "glDeleteTextures",
        "glAreTexturesResident",
        "glPrioritizeTextures",
    }:
        return "gl_count(n)", False
    if name.startswith("glPixelMap"):
        return "gl_count(mapsize)", False
    if name.startswith("glGetPixelMap"):
        return "gl_pixel_map_count(ctx, map)", False
    if name.startswith("glGetMap"):
        return "gl_map_query_count(ctx, target, query)", False
    if name.startswith("glMap1"):
        return "gl_map_count(target, stride, order, 0, 1)", False
    if name.startswith("glMap2"):
        return "gl_map_count(target, ustride, uorder, vstride, vorder)", False
    if "TexLevelParameter" in name:
        return "1", False
    if any(
        part in name for part in ["Material", "Light", "Fog", "TexEnv", "TexGen", "TexParameter"]
    ):
        return "gl_parameter_count(pname)", False
    if name == "glCallLists":
        return "gl_list_bytes(n, type)", True
    if name in {"glGetPolygonStipple", "glPolygonStipple"}:
        return (
            f"gl_pixel_bytes(ctx, 32, 32, GL_COLOR_INDEX, GL_BITMAP, {int(name.startswith('glGet'))})",
            True,
        )
    if name == "glBitmap":
        return "gl_pixel_bytes(ctx, width, height, GL_COLOR_INDEX, GL_BITMAP, 0)", True
    if name == "glGetTexImage":
        return "gl_texture_bytes(ctx, target, level, format, type)", True
    if name in {
        "glTexImage1D",
        "glTexSubImage1D",
        "glTexImage2D",
        "glTexSubImage2D",
        "glDrawPixels",
        "glReadPixels",
    }:
        height = "height" if "2D" in name or "Pixels" in name else "1"
        return (
            f"gl_pixel_bytes(ctx, width, {height}, format, type, {int(name == 'glReadPixels')})",
            True,
        )
    raise ValueError(f"{name}.{argument}: missing pointer extent policy")


def render(schema):
    functions = schema["functions"]
    dispatch = [
        NOTICE,
        GENERATED,
        "#ifndef TWOINE_GL_DISPATCH_H\n#define TWOINE_GL_DISPATCH_H\n#include <stdint.h>\n",
        "typedef struct LxHostGlApi\n{\n",
    ]
    loads = [NOTICE, GENERATED]
    wire = [NOTICE, GENERATED]
    entries = [NOTICE, GENERATED]
    for function in functions:
        name, result, arguments = function["name"], function["result"], function["arguments"]
        signature = ", ".join(f"{kind} {arg}" for kind, arg in arguments) or "void"
        dispatch.append(f"    {result} (*{name})({signature});\n")
        loads.append(f"    LOAD_GL({name});\n")
        size = sum(8 if kind == "double" else 4 for kind, _ in arguments)
        entries.append(
            f'    {{"{name}", call_{name}, {size}, {schema["ordinals"]["warp"].get(name, 0)}, {schema["ordinals"]["gold11"].get(name, 0)}}},\n'
        )
        if name in CUSTOM:
            continue
        wire.append(
            f"static uint32_t call_{name}(uint8_t *a)\n{{\n    (void)a;\n    GlContext *ctx = gl_current();\n    if (!ctx) return 0;\n"
        )
        if name in {"glViewport", "glClear", "glBegin", "glNewList"}:
            wire.append("    if (!gl_resize_current(ctx)) return 0;\n")
        pointers = []
        offset = 0
        for kind, arg in arguments:
            if "*" in kind:
                wire.append(f"    uint32_t {arg}_address = gl_word(a, {offset});\n")
                pointers.append((kind, arg))
            else:
                decode = (
                    "gl_double"
                    if kind == "double"
                    else "gl_float"
                    if kind == "float"
                    else "gl_word"
                )
                wire.append(f"    {kind} {arg} = ({kind}){decode}(a, {offset});\n")
            offset += 8 if kind == "double" else 4
        if name == "glBegin":
            wire.append("    if (ctx->inside) { gl_error(GL_INVALID_OPERATION); return 0; }\n")
        if pointers:
            wire.append(
                "    if (ctx->inside) { gl_error(GL_INVALID_OPERATION); return 0; }\n"
                if not re.fullmatch(
                    r"gl(?:Color|Normal|Vertex|TexCoord|Index|RasterPos|EvalCoord|EdgeFlag|Rect).*v",
                    name,
                )
                else ""
            )
        if name == "glEnd":
            wire.append("    if (!ctx->inside) { gl_error(GL_INVALID_OPERATION); return 0; }\n")
        for _kind, arg in pointers:
            wire.append(f"    GlMemory {arg}_memory = {{0}};\n")
        for kind, arg in pointers:
            length, bytes_ = pointer_size(name, arg)
            base = kind.replace("const", "").replace("*", "").strip()
            factor = 1 if bytes_ else element_size(base)
            output = not kind.startswith("const")
            nullable = name in {"glTexImage1D", "glTexImage2D"}
            wire.append(
                f"    if (!gl_memory({arg}_address, ({length}), {factor}, {int(output)}, {int(nullable)}, &{arg}_memory)) goto done;\n"
            )
        arglist = ", ".join(
            f"({kind}){arg}_memory.host" if "*" in kind else arg for kind, arg in arguments
        )
        prefix = "" if result == "void" else "uint32_t result = (uint32_t)"
        wire.append(f"    {prefix}ctx->api->{name}({arglist});\n")
        for kind, arg in pointers:
            if not kind.startswith("const"):
                wire.append(f"    {arg}_memory.commit = 1;\n")
        if name == "glBegin":
            wire.append("    if (mode <= GL_POLYGON) ctx->inside = 1;\n")
        elif name == "glEnd":
            wire.append("    ctx->inside = 0;\n")
        elif name in {"glFlush", "glFinish"}:
            wire.append("    if (!ctx->config.double_buffer && !ctx->inside) gl_present(ctx, 0);\n")
        if name in {"glGetIntegerv", "glGetFloatv", "glGetDoublev", "glGetBooleanv"}:
            # The private FBO's attachment enums are not guest-visible buffers.
            wire.append(
                f"    gl_fix_query(ctx, pname, params_memory.host, {element_size(arguments[-1][0].replace('const', '').replace('*', '').strip())}, {int(name in {'glGetFloatv', 'glGetDoublev'})});\n"
            )
        if pointers:
            wire.append("done:\n")
            for _, arg in reversed(pointers):
                wire.append(f"    gl_memory_finish(&{arg}_memory);\n")
            if result != "void":
                # Non-void pointer APIs need an initialized result before a failed borrow.
                text = "".join(wire)
                text = text.replace(
                    f"static uint32_t call_{name}(uint8_t *a)\n{{\n",
                    f"static uint32_t call_{name}(uint8_t *a)\n{{\n    uint32_t result = 0;\n",
                )
                text = text.replace(
                    f"uint32_t result = (uint32_t)ctx->api->{name}",
                    f"result = (uint32_t)ctx->api->{name}",
                )
                wire = [text]
        wire.append(f"    return {'0' if result == 'void' else 'result'};\n}}\n")
    dispatch.append("} LxHostGlApi;\n#endif\n")
    constants = [
        NOTICE,
        GENERATED,
        "#ifndef TWOINE_GL_CONSTANTS_H\n#define TWOINE_GL_CONSTANTS_H\n",
    ]
    for name, value in sorted(schema["constants"].items()):
        constants.append(f"#define {name} 0x{value:X}u\n")
    constants.append("#endif\n")
    custom = [NOTICE, GENERATED]
    custom += [f"uint32_t call_{name}(uint8_t *a);\n" for name in sorted(CUSTOM)]
    pgl = [NOTICE, GENERATED]
    implementations = {
        "pglCreateContext": ("create", 16),
        "pglMakeCurrent": ("make_current", 12),
        "pglChooseConfig": ("choose", 8),
        "pglQueryConfigs": ("query_configs", 4),
        "pglDestroyContext": ("destroy", 8),
        "pglCopyContext": ("unsupported", 16),
        "pglIsIndirect": ("indirect", 8),
        "pglSelectColorIndexPalette": ("unsupported", 12),
        "pglUseFont": ("unsupported", 28),
        "pglGetCurrentContext": ("current_context", 4),
        "pglGetCurrentWindow": ("current_window", 4),
        "pglWaitGL": ("wait_gl", 4),
        "pglWaitPM": ("wait_pm", 4),
        "pglSwapBuffers": ("swap", 8),
        "pglQueryCapability": ("capability", 4),
        "pglQueryVersion": ("version", 12),
        "pglUsePMBitmapFont": ("unsupported", 20),
        "pglGrabFrontBitmap": ("unsupported", 12),
        "pglReleaseFrontBitmap": ("unsupported", 4),
    }
    for name, (implementation, size) in implementations.items():
        pgl.append(
            f'    {{"{name}", {implementation}, {size}, {schema["ordinals"]["warp"][name]}, {schema["ordinals"]["gold11"][name]}}},\n'
        )
    return {
        "hal/include/hal/gl_dispatch.h": "".join(dispatch),
        "hal/mesa/gl_load.h": "".join(loads),
        "guest/bindings/opengl.h": "".join(wire),
        "os2libs/generated/opengl-entries.h": "".join(entries),
        "os2libs/generated/opengl-custom.h": "".join(custom),
        "os2libs/generated/pgl-entries.h": "".join(pgl),
        "hal/include/hal/gl_constants.h": "".join(constants),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = False
    for relative, content in render(
        json.loads((ROOT / "tools/data/opengl.json").read_text())
    ).items():
        path = ROOT / relative
        if not path.exists() or path.read_text() != content:
            stale = True
            print(f"{relative}: {'out of date' if args.check else 'updated'}")
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content)
    return int(args.check and stale)


if __name__ == "__main__":
    raise SystemExit(main())
