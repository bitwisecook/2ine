"""Collect license texts of the Rust crates linked into the GNOME frontend."""

import argparse
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs/licenses/rust-crates.txt"
NAMES = ("license", "licence", "copying", "notice", "copyright")


def crates():
    """Normal (non-build, non-dev) dependencies of the frontend, from Cargo metadata."""
    metadata = json.loads(
        subprocess.run(
            [
                "cargo",
                "metadata",
                "--format-version",
                "1",
                "--locked",
                "--offline",
                "--manifest-path",
                str(ROOT / "gnome/Cargo.toml"),
                "--filter-platform",
                "x86_64-unknown-linux-gnu",
            ],
            check=True,
            capture_output=True,
            text=True,
        ).stdout
    )
    packages = {package["id"]: package for package in metadata["packages"]}
    nodes = {node["id"]: node for node in metadata["resolve"]["nodes"]}
    root = metadata["resolve"]["root"]
    linked, queue = set(), [root]
    while queue:
        node = nodes[queue.pop()]
        for dependency in node["deps"]:
            if any(kind["kind"] is None for kind in dependency["dep_kinds"]):
                if dependency["pkg"] not in linked:
                    linked.add(dependency["pkg"])
                    queue.append(dependency["pkg"])
    return sorted((packages[item] for item in linked), key=lambda p: (p["name"], p["version"]))


def generate():
    sections = [
        "Rust crates statically linked into the 2ine GNOME frontend (2ine-ball).\n"
        "Generated by tools/rust_licenses.py from gnome/Cargo.lock.\n"
    ]
    for package in crates():
        directory = Path(package["manifest_path"]).parent
        texts = sorted(
            path
            for path in directory.iterdir()
            if path.is_file() and path.name.lower().startswith(NAMES)
        )
        header = f"{package['name']} {package['version']} — {package.get('license') or 'see text'}"
        source = package.get("repository") or "https://crates.io/crates/" + package["name"]
        body = "\n\n".join(path.read_text(errors="replace").strip() for path in texts)
        sections.append(
            "=" * 78 + f"\n{header}\n{source}\n" + "=" * 78 + "\n" + (body or "(no license file)")
        )
    return "\n\n".join(sections) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the notice is stale")
    args = parser.parse_args()
    text = generate()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != text:
            raise SystemExit(f"{OUTPUT} is out of date; run tools/rust_licenses.py")
        return
    OUTPUT.write_text(text)
    print(OUTPUT)


if __name__ == "__main__":
    main()
