UCHAR WinCpTranslateChar(HAB hab, ULONG source, UCHAR character, ULONG destination)
{
    AnchorBlock *anchor = getAnchorBlock(hab);
    int from = -1, to = -1;
    for (int i = 0; i < 3; i++)
    {
        if (codepages[i] == source)
            from = i;
        if (codepages[i] == destination)
            to = i;
    }
    if (from < 0 || to < 0)
    {
        if (anchor)
            lxHostThreadState()->pm_error = from < 0 ? 0x101D : 0x101E;
        return 0;
    }
    if (from == to)
        return character;
    int table = from * 2 + (to > from ? to - 1 : to);
    return translations[table][character];
}

BOOL WinCpTranslateString(HAB hab, ULONG from, PSZ input, ULONG to, ULONG capacity, PSZ output)
{
    if (!getAnchorBlock(hab) || !input || !output)
        return FALSE;
    /* An invalid code page leaves its own error from the character translator. */
    if (from != to && !WinCpTranslateChar(hab, from, ' ', to))
        return FALSE;
    for (ULONG i = 0; i < capacity; i++)
    {
        UCHAR c = (UCHAR)input[i];
        if (!c)
        {
            output[i] = 0;
            return TRUE;
        }
        output[i] = from == to ? c : WinCpTranslateChar(hab, from, c, to);
        if (!output[i])
            return FALSE;
    }
    if (capacity)
        output[capacity - 1] = 0;
    WinSetErrorInfo(PMERR_PARAMETER_OUT_OF_RANGE, 0);
    return FALSE;
}

PSZ WinNextChar(HAB hab, ULONG cp, ULONG country, PSZ text)
{
    /* Single-byte code pages only; an unknown page falls back to the queue page. */
    (void)hab;
    (void)cp;
    (void)country;
    return text ? text + (*text != 0) : NULL;
}

BOOL WinSetCp(HMQ queue, ULONG cp)
{
    AnchorBlock *a = getAnchorBlockNoHAB();
    if (!cp)
        cp = GProcessState.process_codepage ? GProcessState.process_codepage : 437;
    if (!a || a->message_queue.hmq != queue || (cp != 437 && cp != 850 && cp != 1004))
        return FALSE;
    a->message_queue.codepage = cp;
    return TRUE;
}

BOOL lx_pm_set_cp(HPS handle, ULONG codepage)
{
    PresentationSpace *ps = lx_pm_font_space(handle);
    if (!ps || (codepage && codepage != 437))
        return FALSE;
    ps->codepage = codepage ? codepage : 437;
    return TRUE;
}

ULONG lx_pm_query_cp(HPS handle)
{
    PresentationSpace *ps = lx_pm_font_space(handle);
    return ps ? ps->codepage : 0;
}

ULONG WinQueryCp(HMQ queue)
{
    TRACE_NATIVE("WinQueryCp(%u)", queue);
    AnchorBlock *anchor = getAnchorBlockNoHAB();
    if (!anchor)
        return 0;
    if (!queue || anchor->message_queue.hmq != queue)
        SET_WIN_ERROR_AND_RETURN(anchor, PMERR_INVALID_HMQ, 0);
    return anchor->message_queue.codepage ? anchor->message_queue.codepage : 437;
}

