/* The country file knows the United States (country 1) and code pages 437
   and 850; 0 selects the system country or the process code page. */
static APIRET country_codepage(ULONG country, ULONG codepage, ULONG *resolved)
{
    if (country != 0 && country != COUNTRY_US)
        return ERROR_NLS_NO_CTRY_CODE;
    if (codepage != 0 && codepage != CODEPAGE_US && codepage != CODEPAGE_MULTILINGUAL)
        return ERROR_CODE_PAGE_NOT_FOUND;
    *resolved =
        codepage ? codepage
                 : (GProcessState.process_codepage ? GProcessState.process_codepage : CODEPAGE_US);
    return NO_ERROR;
}

APIRET DosQueryCollate(ULONG len, PCOUNTRYCODE pcc, PCHAR pch, PULONG dlen)
{
    if (!pcc || !dlen || (!pch && len))
        return ERROR_INVALID_PARAMETER;
    ULONG codepage;
    APIRET result = country_codepage(pcc->country, pcc->codepage, &codepage);
    if (result)
        return result;
    *dlen = NLS_TABLE_SIZE;
    const UCHAR *weights = codepage == CODEPAGE_MULTILINGUAL ? collate_850 : collate_437;
    for (unsigned i = 0; i < len && i < NLS_TABLE_SIZE; i++)
        pch[i] = i >= NLS_ASCII_LIMIT ? weights[i - NLS_ASCII_LIMIT]
                                      : (i >= 'a' && i <= 'z' ? i - ('a' - 'A') : i);
    return len < NLS_TABLE_SIZE ? ERROR_NLS_TABLE_TRUNCATED : NO_ERROR;
}

APIRET16 Dos16GetCollate(USHORT len, PCOUNTRYCODE16 pcc, PCHAR pch, PUSHORT dlen)
{
    if (!pcc || !dlen)
        return ERROR_INVALID_PARAMETER;
    COUNTRYCODE code = {pcc->country, pcc->codepage};
    ULONG actual = 0;
    APIRET result = DosQueryCollate(len, &code, pch, &actual);
    if (!result || result == ERROR_NLS_TABLE_TRUNCATED)
        *dlen = (USHORT)actual;
    return result;
}

/* Neither supported code page is a DBCS code page, so the vector holds no
   lead-byte ranges: only its zero terminator. */
APIRET16 Dos16GetDBCSEv(USHORT buflen, PCOUNTRYCODE16 pcc, PCHAR buf)
{

    TRACE_NATIVE("Dos16GetDBCSEv(%u, %p, %p)", (uint)buflen, pcc, buf);
    if (!pcc)
        return ERROR_INVALID_PARAMETER;
    ULONG codepage;
    APIRET result = country_codepage(pcc->country, pcc->codepage, &codepage);
    if (result)
        return result;
    if (!buf && buflen)
        return ERROR_INVALID_PARAMETER;
    if (buflen)
        memset(buf, '\0', buflen);
    return NO_ERROR;
}

