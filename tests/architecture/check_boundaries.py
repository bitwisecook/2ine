"""Validate component ownership, include style, public host contracts and a source-free root."""

import os
import re
from pathlib import Path

root = Path(__file__).resolve().parents[2]
failures = []

SOURCE_SUFFIXES = {".c", ".h", ".m", ".mm", ".cpp", ".inc"}

# Every top-level directory that holds sources has a role, so a new component is
# placed under the rules below before it can pass.
PORTABLE_COMPONENTS = {"formats", "storage", "emulator", "os2"}
HOST_COMPONENTS = {"host", "ball", "environment", "apps"}
SUPPORT_DIRECTORIES = {"tests", "tools", "cmake", "docs", "snap"}
# Sources built by other toolchains or kept only as reference material.
FOREIGN_DIRECTORIES = {"ports", "research", "third_party"}

# Paths whose sources follow another toolchain's conventions: OS/2 guest
# programs built with OS/2 compilers. Vendored libraries live in third_party/.
FOREIGN_SOURCE_PATHS = ("tests/programs/",)

# Execution backends run guest code on the host CPU or an emulator, so they
# use host APIs, CPU-specific assembly and emulator headers.
EXECUTION_BACKENDS = ("emulator/execution/native_i386/", "emulator/execution/unicorn/")

# Files inside portable components that adapt them to the host: the only
# place such a component may use host APIs.
PORTABLE_HOST_ADAPTERS = ("storage/common/host",) + EXECUTION_BACKENDS

# Portable-component paths that may also branch on the host OS. The native
# backend is Linux-only; the Unicorn backend runs on every host.
PORTABLE_OS_ADAPTERS = ("storage/common/host", "emulator/execution/native_i386/")

# Includes each component may not use: formats/ is self-contained, storage/
# builds on formats/ only, the emulator knows nothing of the OS/2 libraries or
# their bindings, and only the components layered on the ball store (below)
# depend on ball/.
FORBIDDEN_INCLUDES = {
    "formats": ("storage/", "ball/", "host/", "emulator/", "os2/"),
    "storage": ("ball/", "host/", "emulator/", "os2/"),
    "emulator": ("ball/", "os2/"),
    "host": ("ball/", "emulator/", "os2/"),
    "os2": ("ball/",),
}

# The ball store keeps a ball's settings, files and references. The OS/2
# installation manager (environment/) and launch planning (emulator/launch/)
# build on it through ball/store.h; only the JSON facade (ball/facade/)
# composes them. Each path takes the rules of its longest matching prefix:
# included paths matching a pattern are refused.
STORE_CLIENT_BALL_INCLUDES = r"ball/(?!store\.h|platform\.h)"
LAYERED_INCLUDES = {
    "ball/facade/": (r"host/", r"apps/", r"emulator/(?!launch/)", r"os2/(?!config/)"),
    "ball/": (r"environment/", r"emulator/", r"host/", r"apps/", r"os2/(?!config/)"),
    "environment/": (
        r"emulator/",
        r"host/",
        r"apps/",
        r"os2/(?!config/)",
        STORE_CLIENT_BALL_INCLUDES,
    ),
    "emulator/launch/": (
        r"emulator/(?!launch/)",
        r"host/",
        r"apps/",
        r"os2/(?!config/)",
        STORE_CLIENT_BALL_INCLUDES,
    ),
    "emulator/": (r"emulator/launch/", r"environment/"),
    # The loader program enters the emulator through its public headers.
    "apps/lx_loader/": (
        r"emulator/\w+/",
        r"host/\w+/",
        r"ball/",
        r"environment/",
        r"os2/",
        r"storage/",
        r"formats/",
    ),
    # Applications talk to the engine through its JSON ABI only.
    "apps/": (
        r"ball/(?!include/)",
        r"environment/",
        r"emulator/",
        r"host/",
        r"os2/",
        r"storage/",
        r"formats/",
    ),
}

# os2/ follows IBM's component build trees. include/ holds the Toolkit-shaped
# public headers and include/private/ the DDK-style private companions.
# config/ is not an IBM tree: it holds the codecs for the files OS/2 keeps its
# configuration in, shared by the DLLs and the ball's configuration editor.
OS2_GROUPS = {
    "include",
    "config",
    "baseos",
    "ps",
    "wpsh",
    "som",
    "registry",
    "mm",
    "mptn",
    "opengl",
    "thirdparty",
}
# DLL directories whose export table comes from another generator: OPENGL's
# Warp and GOLD ordinal sets are generated by tools/codegen/gen_opengl.py.
OS2_DLLS_WITHOUT_DEFINITION = {"os2/opengl/opengl": "opengl"}
# DLLs that, as in OS/2 Warp 4.52, hold no code: every export forwards to
# the DLL that implements it. Their directory holds only the module
# definition, the forwarder table and its module.c.
OS2_FORWARDER_DLLS = {
    "os2/baseos/quecalls": "DOSCALLS",
    "os2/baseos/sesmgr": "DOSCALLS",
    "os2/baseos/nls": "DOSCALLS",
    "os2/baseos/msg": "DOSCALLS",
    "os2/baseos/viocalls": "DOSCALLS",
    "os2/baseos/kbdcalls": "DOSCALLS",
    "os2/ps/pmgre": "PMMERGE",
    "os2/ps/pmshapi": "PMMERGE",
    "os2/ps/pmwin": "PMMERGE",
    "os2/ps/controls/drag": "PMCTLS",
    "os2/mm/mci/mdm": "MMPM",
    "os2/mm/mmio/mmio": "MMPM",
}
OS2_FORWARDER_FILES = {"module.c", "README.md"}
# Exports that a DLL with code of its own forwards, as in Warp 4.52: the
# export names matching the pattern must forward to the named DLL.
OS2_PARTIAL_FORWARDERS = {
    "os2/ps/awe/pmwinx.def": (r"REG(?!ISTER)[A-Z]*", "REGISTRY"),
}
# Static helper code shared by several DLLs of one group, outside any DLL.
OS2_SHARED = (
    "os2/config/",
    "os2/ps/common/",
    "os2/mm/midi/",
    "os2/mm/video/decode/",
    "os2/mptn/common/",
)
# Internal headers one DLL may take from another DLL's directory, with the
# number of such includes; a count change fails. None remain: internals that
# several DLLs share are declared in os2/include/private/ (pmp.h, pmwinp.h,
# pmgrep.h, pmgpip.h, pmwctlp.h, ...).
OS2_CROSS_DLL_ALLOWANCES = {}

# Layers inside emulator/, lowest first. The execution core and backends and
# the guest ABI helpers know no process state; the process runtime (lib2ine)
# knows no loader internals or module records; the loader uses the process
# runtime only through its public headers.
PROCESS_HEADERS = (
    r"emulator/(?:runtime|process|paths|features|audio_mixer|launch_record|resolver_files)\.h"
)
EMULATOR_LAYERS = {
    "emulator/execution/": (
        r"emulator/(?:process|loader|abi)/",
        PROCESS_HEADERS,
        r"emulator/module\.h",
    ),
    "emulator/abi/": (r"emulator/(?:process|loader)/", PROCESS_HEADERS, r"emulator/module\.h"),
    "emulator/include/emulator/abi.h": (r"emulator/",),
    "emulator/include/emulator/arguments.h": (r"emulator/(?!execution\.h)",),
    "emulator/include/emulator/handles.h": (r"emulator/",),
    "emulator/include/emulator/execution.h": (r"emulator/",),
    "emulator/process/": (r"emulator/loader/", r"emulator/module\.h"),
    "emulator/include/emulator/runtime.h": (r"emulator/loader/", r"emulator/module\.h"),
    "emulator/include/emulator/process.h": (r"emulator/loader/", r"emulator/module\.h"),
    "emulator/loader/": (r"emulator/process/",),
}

# Inline assembly belongs to the native i386 backend alone.
ASSEMBLY = r"\b(?:__asm__|__asm|asm)\b\s*(?:__volatile__|volatile)?\s*\("

# Host adapters, one directory each below host/, mirroring host/core/ by
# function. Only the OS adapters may branch on the host operating system.
HOST_OS_ADAPTERS = {"linux", "macos", "win"}
HOST_ADAPTERS = HOST_OS_ADAPTERS | {"posix", "sdl", "openssl", "freetype", "curses", "mesa", "none"}
HOST_FUNCTIONS = {
    "system",
    "process",
    "thread",
    "ipc",
    "fs",
    "net",
    "fatal",
    # Desktop dialogs run in a separate helper process (2ine-dialog on Linux).
    "dialog",
    "window",
    "input",
    "desktop",
    "audio",
    "clipboard",
    "print",
    "terminal",
    "font",
    "opengl",
}

# An adapter may include public headers, host/core/ and itself. The Linux and
# macOS adapters also build on the shared POSIX adapter.
HOST_ADAPTER_INCLUDES = {"linux": {"posix"}, "macos": {"posix"}}

# Host-OS branches that remain outside the platform directories, with the
# number of branch directives each one holds. A count change fails, so an entry
# is removed together with its branches.
TEMPORARY_OS_BRANCH_ALLOWANCES = {}

# Public host contracts, the only host headers portable components include.
PUBLIC_HOST_HEADERS = (
    r"(?:abi|audio|clipboard|clock|codepage_tables|desktop|fatal|font|fs|input|library|mailbox"
    r"|memory|network|opengl|print|process|process_supervisor|shared_memory|socket|sync"
    r"|system|terminal|thread|tls|video_frame|window|gl/(?:dispatch|constants))\.h"
)

# Headers generated into the build tree rather than the source tree.
GENERATED_INCLUDES = {"twoine_ball_icon_png.h"}

INCLUDE_ROOTS = (root, root / "host/include", root / "storage/include", root / "emulator/include")


def excluded_top_level(name):
    return name.startswith((".", "build", "cmake-")) or name == "_deps"


def sources(directory="", suffixes=SOURCE_SUFFIXES):
    """Yield source files below directory without following symbolic links."""
    base = root / directory
    for current, directories, files in os.walk(base):
        here = Path(current)
        if here == root:
            directories[:] = [name for name in directories if not excluded_top_level(name)]
        directories.sort()
        for name in sorted(files):
            path = here / name
            if path.suffix in suffixes:
                yield path


def relative(path):
    return path.relative_to(root).as_posix()


def check(path, patterns, cmake=False):
    if cmake:
        text = re.sub(r"#[^\n]*", "", path.read_text())
    else:
        text = path.read_text()
        text = re.sub(r'(#\s*include\s*)"([^"]+)"', r"\1<\2>", text)
        text = re.sub(
            r"""/\*.*?\*/|//[^\n]*|"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*' """.rstrip(),
            lambda m: (
                "\n" * m.group(0).count("\n") if not m.group(0).startswith(('"', "'")) else "STRING"
            ),
            text,
            flags=re.S,
        )
    found = 0
    for pattern in patterns:
        for match in re.finditer(pattern, text):
            found += 1
            line = text[: match.start()].count("\n") + 1
            failures.append(f"{relative(path)}:{line}: {match.group(0)}")
    return found


def check_include_style(path):
    """Project includes name their path from the project root or host/include."""
    text = path.read_text(errors="replace")
    pattern = r'^[ \t]*#[ \t]*(?:include|import)[ \t]*(?:"([^"]+)"|<([^>]+)>)'
    for match in re.finditer(pattern, text, flags=re.M):
        name = match.group(1) or match.group(2)
        line = text[: match.start()].count("\n") + 1
        where = f"{relative(path)}:{line}: {match.group(0).strip()}"
        if ".." in Path(name).parts:
            failures.append(f"{where}: include by path from the project root, not '../'")
            continue
        if match.group(2) is not None:
            continue
        if name.startswith("host/include/"):
            failures.append(f'{where}: public host headers are included as "host/<name>.h"')
            continue
        if name.startswith("emulator/include/"):
            failures.append(f'{where}: public emulator headers are included as "emulator/<name>.h"')
            continue
        if name.startswith("storage/include/"):
            failures.append(f'{where}: public storage headers are included as "storage/<name>.h"')
            continue
        rooted = [base / name for base in INCLUDE_ROOTS if (base / name).is_file()]
        local = path.parent / name
        if local.is_file() and not any(local.samefile(candidate) for candidate in rooted):
            failures.append(f"{where}: include by path from the project root")
        elif not rooted and not local.is_file() and name not in GENERATED_INCLUDES:
            failures.append(f"{where}: unresolved project include")


def foreign(name):
    return name.split("/", 1)[0] in FOREIGN_DIRECTORIES or name.startswith(FOREIGN_SOURCE_PATHS)


def portable_source(path):
    """Component code that must build on any host without host APIs."""
    name = relative(path)
    return not foreign(name) and not name.startswith(PORTABLE_HOST_ADAPTERS)


def os_branch_scope(path):
    name = relative(path)
    if foreign(name) or name.startswith(PORTABLE_OS_ADAPTERS):
        return False
    top = name.split("/", 1)[0]
    if top in PORTABLE_COMPONENTS:
        return True
    if top != "host":
        return False
    return name.split("/")[1] not in HOST_OS_ADAPTERS


for path in sorted(root.iterdir()):
    if not path.is_dir() or excluded_top_level(path.name):
        continue
    known = PORTABLE_COMPONENTS | HOST_COMPONENTS | SUPPORT_DIRECTORIES | FOREIGN_DIRECTORIES
    if path.name not in known and next(sources(path.name), None):
        failures.append(
            f"{path.name}/: unclassified source directory; add it to check_boundaries.py"
        )

for path in sources():
    name = relative(path)
    if name.split("/", 1)[0] in FOREIGN_DIRECTORIES or name.startswith(FOREIGN_SOURCE_PATHS):
        continue
    check_include_style(path)

platform = [
    r"#\s*include\s*<(?:sys/|asm/|pthread\.h|windows\.h|unicorn/|SDL3/|EGL/|GL/|OpenGL/|vulkan/|Metal/|d3d\w*\.h|curses\.h|arpa/|netinet/|netdb\.h)",
    r"\b(?:ucontext_t|uc_engine|pthread_\w+|SDL_\w+)\b",
]
hardware = platform + [
    r"\b(?:__asm__|syscall|mmap|munmap|mprotect|dlopen|dlsym|dlclose|fork|waitpid)\s*\("
]
for directory in sorted(PORTABLE_COMPONENTS):
    for path in sources(directory, {".c", ".h"}):
        if not portable_source(path):
            continue
        check(
            path,
            hardware + [r"#\s*include\s*<host/(?!" + PUBLIC_HOST_HEADERS + r")[^>]+>"],
        )
for directory, prefixes in sorted(FORBIDDEN_INCLUDES.items()):
    for path in sources(directory):
        # Launch planning is the emulator's client of the ball store.
        if foreign(relative(path)) or relative(path).startswith("emulator/launch/"):
            continue
        check(
            path, [rf"#\s*(?:include|import)\s*<{re.escape(prefix)}[^>]*>" for prefix in prefixes]
        )
for path in sources():
    name = relative(path)
    prefixes = [prefix for prefix in LAYERED_INCLUDES if name.startswith(prefix)]
    if prefixes and not foreign(name):
        rules = LAYERED_INCLUDES[max(prefixes, key=len)]
        check(path, [rf"#\s*(?:include|import)\s*<{pattern}[^>]*>" for pattern in rules])
for path in sources("host/include", {".h"}):
    check(path, platform + [r"\bHANDLE\b"])
# The core holds the platform-free half of each function: no host APIs.
for path in sources("host/core"):
    check(path, hardware)
for path in sources("host"):
    name = relative(path)
    parts = name.split("/")
    if parts[1] == "include" or len(parts) < 4:
        continue
    if parts[1] != "core" and parts[1] not in HOST_ADAPTERS:
        failures.append(f"{name}: unknown host adapter {parts[1]!r}; add it to check_boundaries.py")
    elif parts[2] not in HOST_FUNCTIONS:
        failures.append(
            f"{name}: unknown host function {parts[2]!r}; add it to check_boundaries.py"
        )
    allowed = {"core", parts[1]} | HOST_ADAPTER_INCLUDES.get(parts[1], set())
    text = path.read_text(errors="replace")
    for match in re.finditer(r'^[ \t]*#[ \t]*(?:include|import)[ \t]*"host/(\w+)/', text, re.M):
        if match.group(1) not in allowed and (root / "host" / match.group(1)).is_dir():
            line = text[: match.start()].count("\n") + 1
            failures.append(f"{name}:{line}: {parts[1]} may not include host/{match.group(1)}/")
# Outside host/, only the public contracts are visible.
for path in sources():
    name = relative(path)
    if name.startswith(("host/", "tests/")) or foreign(name):
        continue
    check(
        path,
        [
            r"#\s*(?:include|import)\s*<host/(?:core|"
            + "|".join(sorted(HOST_ADAPTERS))
            + r")/[^>]*>"
        ],
    )
for path in list(sources("host")) + list(sources("emulator/execution")):
    check(path, [r"\b(?:GProcessState|LxModule|LxMmaps)\b"])
for path in sources("emulator"):
    name = relative(path)
    for prefix, banned in EMULATOR_LAYERS.items():
        if name == prefix or (prefix.endswith("/") and name.startswith(prefix)):
            check(path, [rf"#\s*include\s*<{pattern}[^>]*>" for pattern in banned])
for directory in sorted(PORTABLE_COMPONENTS):
    for path in sources(directory, {".c", ".h"}):
        if not relative(path).startswith("emulator/execution/native_i386/"):
            check(path, [ASSEMBLY])
os_branches = [
    r"#\s*(?:if|ifdef|ifndef|elif)\b[^\n]*(?:_WIN32|__APPLE__|__linux__)",
    r"#\s*include\s*<(?:windows\.h|mach/|mach-o/|sys/sysinfo\.h)",
]
for path in sources():
    if not os_branch_scope(path):
        continue
    name = relative(path)
    allowed = TEMPORARY_OS_BRANCH_ALLOWANCES.get(name)
    if allowed is None:
        check(path, os_branches)
        continue
    before = len(failures)
    found = check(path, os_branches)
    if found == allowed:
        del failures[before:]
    else:
        failures.append(f"{name}: {found} host-OS branches; temporary allowance is {allowed}")
for name in TEMPORARY_OS_BRANCH_ALLOWANCES:
    if not (root / name).is_file():
        failures.append(f"{name}: temporary host-OS branch allowance names a missing file")
for directory in sorted(PORTABLE_COMPONENTS):
    base = root / directory
    for path in sorted(base.rglob("CMakeLists.txt")) + sorted(base.rglob("*.cmake")):
        check(
            path,
            [
                r"(?<!tests/)\bhost/(?:core|"
                + "|".join(sorted(HOST_ADAPTERS))
                + r')/[^\s"\)]*\.[chm]\b',
                r"\btwoine_host_(?:function|requires)\b",
            ],
            cmake=True,
        )
for pattern in ["*.c", "*.h", "*.py", "lib*.so*", "*.dll", "os2imports.json"]:
    for path in root.glob(pattern):
        failures.append(f"{path.name}: implementation/tool/data belongs in its component directory")
# Each DLL directory holds one module definition; its generated export table
# sits in generated/ beside it and only the DLL's module.c includes it.
os2_dlls = dict(OS2_DLLS_WITHOUT_DEFINITION)
for path in sorted((root / "os2").glob("**/*.def")):
    directory = relative(path.parent)
    if directory in os2_dlls:
        failures.append(f"{directory}/: one module definition per DLL directory")
    os2_dlls[directory] = path.stem
for path in sorted((root / "os2").glob("**/*-lx.h")):
    if path.parent.name != "generated" or relative(path.parent.parent) not in os2_dlls:
        failures.append(f"{relative(path)}: generated exports belong in <dll>/generated/")
for directory in sorted(OS2_FORWARDER_DLLS):
    dll = root / directory
    definitions = sorted(dll.glob("*.def"))
    if len(definitions) != 1:
        failures.append(f"{directory}/: forwarder DLL without one module definition")
        continue
    definition = definitions[0]
    for line in definition.read_text().splitlines():
        entry = line.split(";", 1)[0].strip()
        target = OS2_FORWARDER_DLLS[directory]
        if entry.endswith(tuple("0123456789")) and "@" in entry and f"= {target}." not in entry:
            failures.append(f"{relative(definition)}: {entry!r} must forward to {target}")
    for path in dll.iterdir():
        if path.name not in OS2_FORWARDER_FILES | {definition.name, "generated"}:
            failures.append(f"{relative(path)}: a forwarder DLL holds no implementation")
for definition, (pattern, target) in sorted(OS2_PARTIAL_FORWARDERS.items()):
    matched = 0
    for line in (root / definition).read_text().splitlines():
        entry = line.split(";", 1)[0].strip()
        if re.fullmatch(pattern, entry.split(" ", 1)[0]) and "@" in entry:
            matched += 1
            if f"= {target}." not in entry:
                failures.append(f"{definition}: {entry!r} must forward to {target}")
    if not matched:
        failures.append(f"{definition}: no export matches {pattern}")
for path in sources("os2"):
    name = relative(path)
    if name.split("/")[1] not in OS2_GROUPS:
        failures.append(f"{name}: unknown os2 group; add it to check_boundaries.py")


def os2_owner(name):
    """The DLL directory or shared helper directory that owns an os2 path."""
    owners = [d for d in os2_dlls if name.startswith(d + "/")]
    if owners:
        return max(owners, key=len)
    for shared in OS2_SHARED:
        if name.startswith(shared):
            return shared.rstrip("/")
    return None


cross_dll = {}
for path in sources("os2"):
    name = relative(path)
    owner = os2_owner(name)
    text = path.read_text(errors="replace")
    for match in re.finditer(r'^[ \t]*#[ \t]*include[ \t]*"(os2/[^"]+)"', text, re.M):
        target = match.group(1)
        line = text[: match.start()].count("\n") + 1
        if target.endswith("-lx.h"):
            if not (owner and name == owner + "/module.c" and target.startswith(owner + "/")):
                failures.append(f"{name}:{line}: only the DLL's module.c includes {target}")
            continue
        if target.startswith("os2/include/"):
            continue
        target_owner = os2_owner(target)
        if target_owner is None:
            failures.append(f"{name}:{line}: {target} belongs to no DLL or shared directory")
        elif target_owner != owner and target_owner + "/" not in OS2_SHARED:
            cross_dll[(owner, target_owner)] = cross_dll.get((owner, target_owner), 0) + 1
for pair, count in sorted(cross_dll.items(), key=str):
    if OS2_CROSS_DLL_ALLOWANCES.get(pair) != count:
        failures.append(
            f"{pair[0]} includes {count} internal headers of {pair[1]}; "
            f"allowance is {OS2_CROSS_DLL_ALLOWANCES.get(pair, 0)}"
        )
for pair in OS2_CROSS_DLL_ALLOWANCES:
    if pair not in cross_dll:
        failures.append(f"{pair}: cross-DLL include allowance names no include")
# Vendored libraries stay as their authors wrote them: they include only their
# own headers and the system's, never project code. Adapters live in the
# component that uses the library.
PROJECT_DIRECTORIES = PORTABLE_COMPONENTS | HOST_COMPONENTS | SUPPORT_DIRECTORIES | {"ports"}
for path in sources("third_party"):
    text = path.read_text(errors="replace")
    for match in re.finditer(r'^[ \t]*#[ \t]*include[ \t]*[<"](\w+)/', text, re.M):
        if match.group(1) in PROJECT_DIRECTORIES:
            line = text[: match.start()].count("\n") + 1
            failures.append(f"{relative(path)}:{line}: third-party code includes project code")
if failures:
    raise SystemExit("\n".join(failures))
print(
    "Source ownership, include style, host-OS branches, public host contracts and root layout passed"
)
