"""Queue-thread Windows timer IDs, replacement, coalescing and TIMERPROC dispatch."""

import struct

from images import FlatGuest, linear_image


def timer_program():
    g = FlatGuest()
    timer, calls = g.field(bytes(4)), g.field(bytes(4))
    message = g.field(bytes(28))
    g.call(2, 653, 0, 0, 1, 0x1122CCDD)
    g.code.extend(b"\xa3" + struct.pack("<I", timer))
    g.require(b"\x85\xc0\x0f\x95\xc0\x3c\x01", 1)
    g.call(2, 653, 0, (timer,), 10, 0x1122CCDD)
    g.require(b"\x3b\x05" + struct.pack("<I", timer), 2)
    g.call(2, 673, 25)
    g.call(2, 513, message, 0, 0x113, 0x113, 0)
    g.result(1, 3)
    g.word(message, 0, 4)
    g.word(message + 4, 0x113, 5)
    g.word(calls, 0, 6)
    g.call(2, 673, 25)
    g.call(2, 513, message, 0, 0x400, 0x400, 0)
    g.result(0, 7)
    g.call(2, 311, message, 0, 0x113, 0x113)
    g.result(1, 8)
    g.load(timer)
    g.require(b"\x3b\x05" + struct.pack("<I", message + 8), 9)
    g.call(2, 452, 0, (timer,))
    g.result(1, 10)
    g.call(2, 149, message)
    g.result(0, 11)
    g.word(calls, 1, 12)
    g.call(2, 513, message, 0, 0x113, 0x113, 1)
    g.result(0, 13)
    g.call(2, 452, 0, (timer,))
    g.result(0, 14)
    g.call(2, 653, 0, 0, 0, 0)
    g.code.extend(b"\xa3" + struct.pack("<I", timer))
    g.require(b"\x85\xc0\x0f\x95\xc0\x3c\x01", 15)
    g.call(2, 673, 25)
    g.call(2, 311, message, 0, 0x113, 0x113)
    g.result(1, 16)
    g.word(message + 12, 0, 17)
    g.call(2, 149, message)
    g.word(calls, 1, 18)
    g.call(2, 452, 0, (timer,))
    g.result(1, 19)
    static = g.field(b"TimerWindow\0")
    record = g.field(struct.pack("<10I", 0, 0x55667788, 0, 0, 0xFFFFFFFF, 0, 0, 0, 0, static))
    g.call(2, 556, record)
    window = g.field(bytes(4))
    g.call(2, 99, 0, static, 0, 0, 0, 0, 80, 40, 0, 0, 0xFFFFFFFF, 0)
    g.code.extend(b"\xa3" + struct.pack("<I", window))
    g.require(b"\x85\xc0\x0f\x95\xc0\x3c\x01", 20)
    g.call(2, 653, (window,), 0x12345678, 10, 0)
    g.result(0x12345678, 21)
    g.call(2, 673, 25)
    g.call(2, 311, message, (window,), 0x113, 0x113)
    g.result(1, 22)
    g.word(message + 8, 0x12345678, 23)
    g.call(2, 452, (window,), 0x12345678)
    g.result(1, 24)
    g.call(2, 653, (window,), 5, 10, 0)
    g.result(5, 25)
    g.call(2, 146, (window,))
    g.result(1, 26)
    g.call(2, 452, (window,), 5)
    g.result(0, 27)
    g.call(2, 653, 0, 0, 10, 0xDEADBEEF)
    g.result(0, 28)
    g.call(2, 300)
    g.result(87, 29)
    g.exit(0)
    callback = 0x10000 + len(g.code)
    g.require(b"\x83\x7c\x24\x04\x00", 30)
    g.require(b"\x81\x7c\x24\x08" + struct.pack("<I", 0x113), 31)
    g.code.extend(b"\x8b\x44\x24\x0c")
    g.require(b"\x3b\x05" + struct.pack("<I", timer), 32)
    g.code.extend(b"\xff\x05" + struct.pack("<I", calls))
    g.call(2, 624, 0xABCD)
    g.code.extend(b"\xc3")
    g.code = g.code.replace(struct.pack("<I", 0x1122CCDD), struct.pack("<I", callback))
    procedure = 0x10000 + len(g.code)
    g.code.extend(b"\x31\xc0\x81\x7c\x24\x08\x81\0\0\0\x0f\x94\xc0\xc3")
    g.data = g.data.replace(struct.pack("<I", 0x55667788), struct.pack("<I", procedure))
    return linear_image(g.code, g.fixups, ["DOSCALLS", "PMWINX"], "TIMER32", data=g.data)
