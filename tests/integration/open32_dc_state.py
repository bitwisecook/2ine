"""Saved DC levels restore selected objects, clip copies and drawing attributes."""

import struct

from images import FlatGuest, linear_image
from open32_contracts import call, store


def dc_state_program():
    g = FlatGuest()
    dc, bitmap, brush, old_brush, font, old_font, region = (g.field(bytes(4)) for _ in range(7))
    logfont = g.field(
        struct.pack("<5i8B32s", -16, 0, 0, 0, 400, 0, 0, 0, 0, 0, 0, 0, 0, b"Courier")
    )
    rectangle = g.field(bytes(16))
    call(g, "CreateCompatibleDC", 0)
    store(g, dc)
    call(g, "CreateBitmap", 32, 24, 1, 24, 0)
    store(g, bitmap)
    call(g, "SelectObject", (dc,), (bitmap,))
    call(g, "CreateSolidBrush", 0xFF)
    store(g, brush)
    call(g, "SelectObject", (dc,), (brush,))
    store(g, old_brush)
    call(g, "CreateFontIndirect", logfont)
    store(g, font)
    call(g, "SelectObject", (dc,), (font,))
    store(g, old_font)
    call(g, "CreateRectRgn", 1, 2, 8, 9)
    store(g, region)
    call(g, "SelectClipRgn", (dc,), (region,))
    g.result(2, 1)
    call(g, "DeleteObject", (region,))
    g.result(1, 2)
    call(g, "SetTextColor", (dc,), 0x123456)
    g.call(2, 576, (dc,))
    g.result(1, 3)
    call(g, "SelectObject", (dc,), (old_brush,))
    call(g, "SelectObject", (dc,), (old_font,))
    for value in (brush, font):
        call(g, "DeleteObject", (value,))
        g.result(0, 4)
    call(g, "SelectClipRgn", (dc,), 0)
    call(g, "SetTextColor", (dc,), 0xABCDEF)
    g.call(2, 576, (dc,))
    g.result(2, 5)
    g.call(2, 572, (dc,), 3)
    g.result(0, 6)
    g.call(2, 572, (dc,), 0xFFFFFFFE)
    g.result(1, 7)
    call(g, "SetTextColor", (dc,), 0)
    g.result(0x123456, 8)
    call(g, "SelectObject", (dc,), (old_font,))
    g.require(b"\x3b\x05" + struct.pack("<I", font), 9)
    call(g, "GetClipBox", (dc,), rectangle)
    g.result(2, 10)
    for offset, value in [(0, 1), (4, 2), (8, 8), (12, 9)]:
        g.word(rectangle + offset, value, 11)
    call(g, "PatBlt", (dc,), 0, 0, 32, 24, 0x00F00021)
    g.result(1, 12)
    call(g, "GetPixel", (dc,), 1, 2)
    g.result(0xFF, 13)
    call(g, "GetPixel", (dc,), 0, 0)
    g.result(0, 14)
    g.call(2, 576, (dc,))
    g.result(1, 15)
    g.call(2, 572, (dc,), 1)
    g.result(1, 16)
    g.call(2, 572, (dc,), 0xFFFFFFFF)
    g.result(0, 17)
    g.call(2, 576, (dc,))
    g.result(1, 18)
    call(g, "DeleteDC", (dc,))
    g.result(1, 19)
    for value in (brush, font, bitmap):
        call(g, "DeleteObject", (value,))
        g.result(1, 20)
    g.call(2, 576, 0xDEADBEEF)
    g.result(0, 21)
    g.exit(0)
    return linear_image(g.code, g.fixups, ["DOSCALLS", "PMWINX"], "SAVEDC32", data=g.data)
