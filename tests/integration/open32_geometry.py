"""Window placements preserve normal geometry and validate the caller's record extent."""

import struct

from images import FlatGuest, linear_image


def placement_program(checked):
    g = FlatGuest()
    name = g.field(b"PlacementWindow\0")
    record = g.field(struct.pack("<10I", 0, 0xABCDEF12, 0, 0, 0xFFFFFFFF, 0, 0, 0, 0, name))
    placement = g.field(struct.pack("<11I", 44, *([0] * 10)))
    window = g.field(bytes(4))
    forwarded, previous, replacement = (
        g.field(bytes(4)),
        g.field(bytes(4)),
        g.field(struct.pack("<I", 0xABCDEF13)),
    )
    g.call(2, 556, record)
    g.call(2, 99, 0, name, 0, 0xCF0000, 10, 20, 100, 50, 0, 0, 0xFFFFFFFF, 0)
    g.code.extend(b"\xa3" + struct.pack("<I", window))
    client, child = g.field(bytes(4)), g.field(bytes(4))
    g.call(3, 899, (window,), 0x8008)
    g.code.extend(b"\xa3" + struct.pack("<I", client))
    g.require(b"\x85\xc0\x0f\x95\xc0\x3c\x01", 16)
    g.load(client)
    g.require(b"\x3b\x05" + struct.pack("<I", window) + b"\x0f\x95\xc0\x3c\x01", 17)
    g.call(3, 834, (client,), 5)  # Native QW_PARENT
    g.require(b"\x3b\x05" + struct.pack("<I", window), 18)
    g.call(2, 99, 0, name, 0, 0x50000000, 3, 4, 20, 10, (window,), 33, 0xFFFFFFFF, 0)
    g.code.extend(b"\xa3" + struct.pack("<I", child))
    g.call(3, 834, (child,), 5)
    g.require(b"\x3b\x05" + struct.pack("<I", client), 19)
    g.call(2, 333, (child,))
    g.require(b"\x3b\x05" + struct.pack("<I", window), 20)
    g.call(2, 273, (window,), 33)
    g.require(b"\x3b\x05" + struct.pack("<I", child), 21)
    g.call(2, 382, (window,), 5)  # Windows GW_CHILD
    g.require(b"\x3b\x05" + struct.pack("<I", child), 22)
    g.call(2, 146, (child,))
    g.result(1, 23)
    g.call(3, 920, (client,), 0x1044, 0, 0)
    g.word(forwarded, 1, 45)
    g.call(3, 929, (window,), (replacement,))
    g.code.extend(b"\xa3" + struct.pack("<I", previous))
    g.call(3, 920, (client,), 0x1044, 0, 0)
    g.word(forwarded, 1, 46)
    g.call(3, 929, (window,), (previous,))
    g.call(3, 920, (client,), 0x1044, 0, 0)
    g.word(forwarded, 2, 47)
    g.call(2, 387, (window,), placement)
    g.result(1, 1)
    g.word(placement + 8, 1, 2)
    for index, value in enumerate((10, 20, 110, 70)):
        g.word(placement + 28 + 4 * index, value, 3)
    g.call(2, 451, (window,))
    g.result(0, 8)
    flags, frame = (g.field(bytes(4)) for _ in range(2))
    g.call(3, 908, 1, 0, flags, 0, name, 0, 0, 0, 0)
    g.code.extend(b"\xa3" + struct.pack("<I", frame))
    g.call(3, 875, (frame,), 3, 0, 0, 100, 50, 1)
    g.result(1, 12)
    g.call(3, 875, (frame,), 3, 0, 0, 0, 0, 0x800)
    g.result(1, 13)
    g.call(2, 451, (frame,))
    g.result(1, 9)
    g.call(3, 875, (frame,), 3, 0, 0, 0, 0, 0x1000)
    g.result(1, 14)
    g.call(2, 451, (frame,))
    g.result(0, 10)
    g.call(2, 451, 0xFFFFFFFF)
    g.result(0, 11)
    g.call(3, 728, (frame,))
    g.result(1, 15)
    g.code.extend(b"\xc7\x05" + struct.pack("<II", placement, 43))
    g.call(2, 387, (window,), placement)
    g.result(0, 4)
    g.call(2, 300)
    g.result(87, 5)
    if checked:
        g.call(2, 387, (window,), 0xFFFFFFFF)
        g.result(0, 6)
    menu, space = g.field(bytes(4)), g.field(bytes(4))
    rectangle = g.field(bytes(16))
    label = g.field(b"&File\0")
    g.call(2, 82)
    g.code.extend(b"\xa3" + struct.pack("<I", menu))
    g.call(2, 9, (menu,), 0, 99, label)
    g.result(1, 24)
    mdi_class, mdi = g.field(b"MDICLIENT\0"), g.field(bytes(4))
    g.call(2, 99, 0, mdi_class, 0, 0x50000000, 0, 0, 20, 10, (window,), 34, 0xFFFFFFFF, 0)
    g.code.extend(b"\xa3" + struct.pack("<I", mdi))
    g.call(2, 588, (mdi,), 0x230, (menu,), 0)  # WM_MDISETMENU
    g.result(0, 43)
    g.call(2, 628, (window,), (menu,))
    g.result(1, 25)
    g.call(2, 305, (window,))
    g.require(b"\x3b\x05" + struct.pack("<I", menu), 26)
    g.call(3, 899, (window,), 0x8005)
    g.require(b"\x3b\x05" + struct.pack("<I", menu), 27)
    g.call(2, 244, (window,), rectangle)
    g.result(1, 28)
    g.word(rectangle + 12, 26, 29)
    g.call(2, 263, (window,))
    g.code.extend(b"\xa3" + struct.pack("<I", space))
    g.call(4, 444, (space,))
    g.require(b"\x3b\x05" + struct.pack("<I", client), 30)
    g.call(2, 560, (window,), (space,))
    g.result(1, 31)
    g.call(2, 628, (window,), 0x12345678)
    g.result(0, 32)
    g.call(2, 305, (window,))
    g.require(b"\x3b\x05" + struct.pack("<I", menu), 33)
    g.call(2, 628, (window,), 0)
    g.result(1, 34)
    g.call(2, 446, (menu,))
    g.result(1, 35)
    g.call(2, 244, (window,), rectangle)
    g.result(1, 36)
    g.word(rectangle + 12, 50, 37)
    g.call(2, 146, (mdi,))
    g.result(1, 44)
    g.call(2, 145, (menu,))
    g.result(1, 38)
    helpfile = g.field(b"MISSING.HLP\0")
    g.call(2, 715, 0, helpfile, 2, 0)
    g.result(1, 39)
    g.call(2, 715, 0, 0, 2, 0)
    g.result(0, 40)
    g.call(2, 715, (window,), helpfile, 1, 0)
    g.result(0, 41)
    g.call(2, 300)
    g.result(50, 42)
    g.call(2, 146, (window,))
    g.result(1, 7)
    g.exit(0)
    callback = 0x10000 + len(g.code)
    g.code.extend(b"\x81\x7c\x24\x08\x44\x04\0\0\x75\x06\xff\x05" + struct.pack("<I", forwarded))
    g.code.extend(b"\x31\xc0\x81\x7c\x24\x08\x81\0\0\0\x0f\x94\xc0\xc3")
    replacement_callback = 0x10000 + len(g.code)
    g.code.extend(b"\x31\xc0\xc3")
    g.data = g.data.replace(struct.pack("<I", 0xABCDEF13), struct.pack("<I", replacement_callback))
    g.data = g.data.replace(struct.pack("<I", 0xABCDEF12), struct.pack("<I", callback))
    return linear_image(
        g.code, g.fixups, ["DOSCALLS", "PMWINX", "PMWIN", "PMGPI"], "PLACEMENT32", data=g.data
    )
