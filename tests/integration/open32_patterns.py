"""Pattern brush ownership, monochrome expansion, clipping and source-free ROPs."""

import struct

from images import FlatGuest, linear_image
from open32_contracts import call, store


def pattern_program():
    g = FlatGuest()
    screen, dc, bitmap, brush, previous = (g.field(bytes(4)) for _ in range(5))
    tile = g.field(bytes.fromhex("80004000"))
    info = g.field(bytes(12))
    rect = g.field(struct.pack("<4i", 3, 2, 7, 6))
    call(g, "GetDC", 0)
    store(g, screen)
    call(g, "CreateCompatibleDC", (screen,))
    store(g, dc)
    call(g, "CreateBitmap", 2, 2, 1, 1, tile)
    store(g, bitmap)
    call(g, "CreatePatternBrush", (bitmap,))
    store(g, brush)
    call(g, "DeleteObject", (bitmap,))
    g.result(1, 1)
    call(g, "GetObject", (brush,), 12, info)
    g.result(12, 2)
    g.word(info, 3, 3)
    g.load(info + 8)
    g.require(b"\x3b\x05" + struct.pack("<I", bitmap), 4)
    call(g, "CreateCompatibleBitmap", (screen,), 8, 8)
    store(g, bitmap)
    call(g, "SelectObject", (dc,), (bitmap,))
    call(g, "SelectObject", (dc,), (brush,))
    store(g, previous)
    call(g, "SetTextColor", (dc,), 0xFF)
    call(g, "SetBkColor", (dc,), 0xFF0000)
    call(g, "SetROP2", (dc,), 7)
    call(g, "PatBlt", (dc,), 0, 0, 8, 8, 0xF00021)
    g.result(1, 5)
    for x, y, color in ((0, 0, 0xFF), (1, 0, 0xFF0000), (0, 1, 0xFF0000), (7, 7, 0xFF)):
        call(g, "GetPixel", (dc,), x, y)
        g.result(color, 6)
    origin = g.field(bytes(8))
    call(g, "SetBrushOrgEx", (dc,), 1, 0, origin)
    g.result(1, 22)
    g.word(origin, 0, 23)
    call(g, "GetBrushOrgEx", (dc,), origin)
    g.result(1, 24)
    g.word(origin, 1, 25)
    call(g, "PatBlt", (dc,), 0, 0, 8, 8, 0xF00021)
    call(g, "GetPixel", (dc,), 0, 0)
    g.result(0xFF0000, 26)
    call(g, "SetBrushOrgEx", (dc,), 0, 0, 0)
    call(g, "PatBlt", (dc,), 0, 0, 8, 8, 0xF00021)
    call(g, "PatBlt", (dc,), 0, 0, 8, 8, 0x5A0049)
    g.result(1, 7)
    call(g, "GetPixel", (dc,), 1, 0)
    g.result(0, 8)
    call(g, "PatBlt", (dc,), 0, 0, 8, 8, 0x550009)
    call(g, "GetPixel", (dc,), 1, 0)
    g.result(0xFFFFFF, 9)
    call(g, "PatBlt", (dc,), 0, 0, 8, 8, 0x000042)
    call(g, "PatBlt", (dc,), 0, 0, 8, 8, 0xCC0020)
    g.result(0, 10)
    call(g, "GetLastError")
    g.result(87, 11)
    call(g, "FillRect", (dc,), rect, (brush,))
    g.result(1, 12)
    call(g, "GetPixel", (dc,), 3, 2)
    g.result(0xFF0000, 13)
    call(g, "GetPixel", (dc,), 2, 2)
    g.result(0, 14)
    call(g, "IntersectClipRect", (dc,), 0, 0, 4, 4)
    call(g, "PatBlt", (dc,), 0, 0, 8, 8, 0xFF0062)
    call(g, "SelectClipRgn", (dc,), 0)
    call(g, "GetPixel", (dc,), 3, 3)
    g.result(0xFFFFFF, 15)
    call(g, "GetPixel", (dc,), 4, 3)
    g.result(0xFF0000, 16)
    call(g, "SelectObject", (dc,), (previous,))
    call(g, "DeleteObject", (brush,))
    g.result(1, 17)
    triangle = g.field(struct.pack("<6i", 1, 1, 7, 1, 1, 7))
    call(g, "CreateSolidBrush", 0xFF)
    store(g, brush)
    call(g, "SelectObject", (dc,), (brush,))
    call(g, "SetROP2", (dc,), 13)
    call(g, "PatBlt", (dc,), 0, 0, 8, 8, 0xFF0062)
    call(g, "Polygon", (dc,), triangle, 3)
    g.result(1, 18)
    for x, y, color in ((2, 2, 0xFF), (3, 1, 0), (6, 6, 0xFFFFFF)):
        call(g, "GetPixel", (dc,), x, y)
        g.result(color, 19)
    call(g, "PatBlt", (dc,), 0, 0, 8, 8, 0x000042)
    call(g, "SetROP2", (dc,), 7)
    for color in (0xFF, 0):
        call(g, "Polygon", (dc,), triangle, 3)
        g.result(1, 20)
        call(g, "GetPixel", (dc,), 2, 2)
        g.result(color, 21)
    call(g, "SelectObject", (dc,), (previous,))
    call(g, "DeleteObject", (brush,))
    call(g, "DeleteDC", (dc,))
    call(g, "DeleteObject", (bitmap,))
    call(g, "ReleaseDC", 0, (screen,))
    g.exit(0)
    return linear_image(g.code, g.fixups, ["DOSCALLS", "PMWINX"], "PATTERN32", data=g.data)
