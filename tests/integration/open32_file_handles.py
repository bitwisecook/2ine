"""Windows file handles use real bytes, sharing, creation dispositions and 64-bit positions."""

import struct

from images import FlatGuest, linear_image


def file_handle_program(checked):
    g = FlatGuest()
    name = g.field(b"windows-file.bin\0")
    handle, second, actual, high = (g.field(bytes(4)) for _ in range(4))
    data = g.field(b"hello\0")
    output = g.field(bytes(32))

    def save(field):
        g.code.extend(b"\xa3" + struct.pack("<I", field))

    g.call(2, 74, name, 0xC0000000, 0, 0, 1, 0x80, 0)
    save(handle)
    g.require(b"\x83\xf8\xff\x0f\x95\xc0\x3c\x01", 1)
    g.call(2, 74, name, 0x80000000, 3, 0, 3, 0x80, 0)
    g.result(0xFFFFFFFF, 2)
    g.call(2, 300)
    g.result(32, 3)
    g.call(2, 717, (handle,), data, 5, actual, 0)
    g.result(1, 4)
    g.word(actual, 5, 5)
    g.call(2, 219, (handle,))
    g.result(1, 6)
    g.call(2, 286, (handle,), high)
    g.result(5, 7)
    g.word(high, 0, 8)
    g.call(2, 618, (handle,), 0, 0, 0)
    g.result(0, 9)
    g.call(2, 535, (handle,), output, 32, actual, 0)
    g.result(1, 10)
    g.word(actual, 5, 11)
    g.word(output, int.from_bytes(b"hell", "little"), 12)
    g.call(2, 618, (handle,), 2, 0, 0)
    g.result(2, 13)
    g.call(2, 613, (handle,))
    g.result(1, 14)
    g.call(2, 286, (handle,), 0)
    g.result(2, 15)
    g.call(2, 289, (handle,))
    g.result(1, 16)
    g.call(2, 44, (handle,))
    g.result(1, 17)
    g.call(2, 74, name, 0x80000000, 1, 0, 4, 0x80, 0)
    save(handle)
    g.call(2, 300)
    g.result(183, 18)
    g.call(2, 74, name, 0x80000000, 1, 0, 3, 0x80, 0)
    save(second)
    g.require(b"\x83\xf8\xff\x0f\x95\xc0\x3c\x01", 19)
    g.call(2, 74, name, 0x40000000, 3, 0, 3, 0x80, 0)
    g.result(0xFFFFFFFF, 20)
    g.call(2, 717, (handle,), data, 1, actual, 0)
    g.result(0, 21)
    g.call(2, 300)
    g.result(5, 22)
    for field in (handle, second):
        g.call(2, 44, (field,))
        g.result(1, 23)
    g.call(2, 74, name, 0xC0000000, 3, 0, 2, 0x80, 0)
    save(handle)
    g.call(2, 300)
    g.result(183, 24)
    g.call(2, 286, (handle,), 0)
    g.result(0, 25)
    g.code.extend(b"\xc7\x05" + struct.pack("<II", high, 1))
    g.call(2, 618, (handle,), 17, high, 0)
    g.result(17, 26)
    g.word(high, 1, 27)
    g.call(2, 613, (handle,))
    g.result(1, 28)
    g.call(2, 286, (handle,), high)
    g.result(17, 29)
    g.word(high, 1, 30)
    g.call(2, 618, (handle,), 0xFFFFFFFF, 0, 0)
    g.result(0xFFFFFFFF, 31)
    g.call(2, 300)
    g.result(131, 32)
    g.call(2, 618, (handle,), 0, 0, 0)
    g.result(0, 33)
    g.call(2, 613, (handle,))
    g.result(1, 34)
    g.call(2, 717, (handle,), data, 5, actual, 0)
    g.result(1, 35)
    if checked:
        g.call(2, 286, (handle,), 0xFFFFFFFF)
        g.result(0xFFFFFFFF, 36)
        g.call(2, 618, (handle,), 0, 0xFFFFFFFF, 0)
        g.result(0xFFFFFFFF, 37)
        g.call(2, 74, name, 0x80000000, 3, 0xFFFFFFFF, 3, 0x80, 0)
        g.result(0xFFFFFFFF, 38)
    g.call(2, 44, (handle,))
    g.result(1, 39)
    g.call(2, 286, (handle,), 0)
    g.result(0xFFFFFFFF, 40)
    g.exit(0)
    return linear_image(g.code, g.fixups, ["DOSCALLS", "PMWINX"], "WINFILES32", data=g.data)


def conversion_program(checked):
    g = FlatGuest()
    oem = g.field(b"Caf\x82\0\xe1!")
    ansi = g.field(b"Caf\xe9\0\xdf!")
    output = g.field(b"XXXXXXXX")
    g.call(2, 495, oem, output)
    g.result(1, 1)
    g.word(output, int.from_bytes(b"Caf\xe9", "little"), 2)
    g.word(output + 4, int.from_bytes(b"\0XXX", "little"), 3)
    g.call(2, 28, ansi, output)
    g.result(1, 4)
    g.word(output, int.from_bytes(b"Caf\x82", "little"), 5)
    g.call(2, 496, oem, output, 7)
    g.result(1, 6)
    g.word(output + 4, int.from_bytes(b"\0\xdf!X", "little"), 7)
    g.call(2, 29, output, output, 7)
    g.result(1, 8)
    g.word(output + 4, int.from_bytes(b"\0\xe1!X", "little"), 9)
    for first, second, expected in [
        (b"a", b"A", 32), (b"A", b"a", -32), (b"a-b", b"ab", -53),
        (b"\xe9", b"e", 132), (b"\x80", b"\xe9", -105), (b"", b"a", -97),
        (b"a_b", b"ab", -3), (b"ab", b"a-b", 53), (b"equal", b"equal", 0),
    ]:
        a, b = g.field(first + b"\0"), g.field(second + b"\0")
        g.call(2, 479, a, b)
        g.result(expected & 0xFFFFFFFF, 12)
    if checked:
        g.call(2, 495, 0xFFFFFFFF, output)
        g.result(0, 10)
        g.call(2, 496, oem, 0xFFFFFFFF, 7)
        g.result(0, 11)
    g.exit(0)
    return linear_image(g.code, g.fixups, ["DOSCALLS", "PMWINX"], "CONVERT32", data=g.data)


def volume_program(checked):
    g = FlatGuest()
    root, missing = g.field(b"C:\\\0"), g.field(b"Z:\\\0")
    label, filesystem = g.field(b"XXXXXXXX"), g.field(b"XXXXXXXX")
    serial, component, flags = (g.field(bytes(4)) for _ in range(3))
    g.call(2, 380, root, label, 4, serial, component, flags, filesystem, 8)
    g.result(0, 1)
    g.word(label, int.from_bytes(b"XXXX", "little"), 2)
    g.call(2, 300)
    g.result(234, 3)
    g.call(2, 380, root, label, 8, serial, component, flags, filesystem, 8)
    g.result(1, 4)
    g.word(label, int.from_bytes(b"2ine", "little"), 5)
    g.word(filesystem, int.from_bytes(b"HPFS", "little"), 6)
    g.word(serial, 0, 7)
    g.word(component, 255, 8)
    g.word(flags, 2, 9)
    g.call(2, 380, missing, 0, 0, 0, 0, 0, 0, 0)
    g.result(0, 10)
    g.call(2, 380, 0, 0, 0, 0, 0, 0, 0, 0)
    g.result(1, 11)
    if checked:
        g.call(2, 380, root, label, 8, 0xFFFFFFFF, component, flags, filesystem, 8)
        g.result(0, 12)
        g.call(2, 380, root, 0xFFFFFFFF, 8, serial, component, flags, filesystem, 8)
        g.result(0, 13)
    g.exit(0)
    return linear_image(g.code, g.fixups, ["DOSCALLS", "PMWINX"], "VOLUME32", data=g.data)
