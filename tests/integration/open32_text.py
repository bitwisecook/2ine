"""Text alignment uses actual character-cell bounds and DC current position."""

import struct

from images import FlatGuest, linear_image
from open32_contracts import call, store


def alignment_program():
    g = FlatGuest()
    screen, dc, bitmap, x, y = (g.field(bytes(4)) for _ in range(5))
    extent, previous = g.field(bytes(8)), g.field(bytes(8))
    metrics = g.field(bytes(56))
    text = g.field(b"  ")
    output = g.field(bytes(32))
    call(g, "GetDC", 0)
    store(g, screen)
    call(g, "CreateCompatibleDC", (screen,))
    store(g, dc)
    call(g, "CreateCompatibleBitmap", (screen,), 64, 64)
    store(g, bitmap)
    call(g, "SelectObject", (dc,), (bitmap,))
    call(g, "SetBkColor", (dc,), 0xFF0000)
    call(g, "GetTextExtentPoint32", (dc,), text, 2, extent)
    g.result(1, 1)
    call(g, "GetTextMetrics", (dc,), metrics)
    g.result(1, 2)
    call(g, "SetTextAlign", (dc,), 2)
    g.result(0, 3)
    call(g, "TextOut", (dc,), 63, 0, text, 2)
    g.result(1, 4)
    for px, color in ((62, 0xFF0000), (63, 0)):
        call(g, "GetPixel", (dc,), px, 0)
        g.result(color, 5)
    call(g, "SetTextAlign", (dc,), 6)
    g.result(2, 6)
    call(g, "TextOut", (dc,), 32, 22, text, 2)
    g.result(1, 7)
    g.load(extent)
    g.code.extend(b"\xd1\xe8\x89\xc1\xb8\x20\0\0\0\x29\xc8")
    store(g, x)
    call(g, "GetPixel", (dc,), (x,), 22)
    g.result(0xFF0000, 8)
    g.code.extend(b"\xff\x0d" + struct.pack("<I", x))
    call(g, "GetPixel", (dc,), (x,), 22)
    g.result(0, 9)
    call(g, "SetTextAlign", (dc,), 24)
    g.result(6, 10)
    call(g, "TextOut", (dc,), 0, 20, text, 2)
    g.result(1, 11)
    g.code.extend(b"\xb8\x14\0\0\0\x2b\x05" + struct.pack("<I", metrics + 4))
    store(g, y)
    call(g, "GetPixel", (dc,), 0, (y,))
    g.result(0xFF0000, 12)
    g.code.extend(b"\xff\x0d" + struct.pack("<I", y))
    call(g, "GetPixel", (dc,), 0, (y,))
    g.result(0, 13)
    call(g, "SetTextAlign", (dc,), 1)
    g.result(24, 14)
    call(g, "MoveToEx", (dc,), 2, 44, 0)
    call(g, "TextOut", (dc,), 999, 999, text, 2)
    g.result(1, 15)
    call(g, "MoveToEx", (dc,), 0, 0, previous)
    g.load(extent)
    g.code.extend(b"\x83\xc0\x02\x3b\x05" + struct.pack("<I", previous))
    g.require(b"", 16)
    g.word(previous + 4, 44, 17)
    call(g, "GetTextAlign", (dc,))
    g.result(1, 18)
    call(g, "GetTextFace", (dc,), 3, output)
    g.result(2, 19)
    g.word(output, int.from_bytes(b"He\0\0", "little"), 20)
    for name in ("IsBadReadPtr", "IsBadWritePtr"):
        call(g, name, 0, 0)
        g.result(0, 21)
        call(g, name, 0, 1)
        g.result(1, 22)
        call(g, name, output, 32)
        g.result(0, 23)
        call(g, name, 0xFFFFFFF0, 32)
        g.result(1, 24)
    call(g, "IsBadCodePtr", output)
    g.result(0, 25)  # Readable i386 LX pages are executable.
    call(g, "IsBadCodePtr", 0xFFFFFFF0)
    g.result(1, 27)
    call(g, "IsBadCodePtr", 0x10000)
    g.result(0, 26)
    mixed = g.field(bytes.fromhex("61007a82"))
    call(g, "CharUpper", ord("q"))
    g.result(ord("Q"), 28)
    call(g, "CharUpper", 0x82)
    g.result(ord("E"), 29)
    call(g, "CharUpperBuff", mixed, 4)
    g.result(4, 30)
    g.word(mixed, 0x455A0041, 31)
    call(g, "CharLowerBuff", mixed, 4)
    g.result(4, 32)
    g.word(mixed, 0x657A0061, 33)
    value = g.field(b"Mixed\0")
    call(g, "CharUpper", value)
    g.result(value, 34)
    g.word(value, int.from_bytes(b"MIXE", "little"), 35)
    call(g, "CharLower", value)
    g.result(value, 36)
    g.word(value, int.from_bytes(b"mixe", "little"), 37)
    call(g, "CharNext", value)
    g.result(value + 1, 38)
    call(g, "CharNext", value + 5)
    g.result(value + 5, 39)
    call(g, "CharPrev", value, value + 2)
    g.result(value + 1, 40)
    call(g, "CharPrev", value, value)
    g.result(value, 41)
    for a, b, expected in (
        (b"Mixed", b"mIXED", 0),
        (b"Z", b"a", 25),
        (b"\x82", b"E", 61),
        (b"", b"\xff", -255),
        (b"abcd", b"abc", 68),
    ):
        left, right = g.field(a + b"\0"), g.field(b + b"\0")
        call(g, "lstrcmpi", left, right)
        g.result(expected & 0xFFFFFFFF, 42)
    call(g, "DeleteDC", (dc,))
    call(g, "DeleteObject", (bitmap,))
    call(g, "ReleaseDC", 0, (screen,))
    g.exit(0)
    return linear_image(g.code, g.fixups, ["DOSCALLS", "PMWINX"], "TEXTALIGN32", data=g.data)
