"""Independent guest processes must observe the same exclusive byte-range locks."""

import struct

from images import FlatGuest, linear_image


def lock_program(child):
    g = FlatGuest()
    name = g.field(b"locked-file.bin\0")
    handle, other, event, actual = (g.field(bytes(4)) for _ in range(4))
    event_name = g.field(b"\\SEM32\\OPEN32_FILE_LOCK_TEST\0")
    data, output = g.field(b"hello"), g.field(bytes(8))
    ready = g.field(b"LOCKED\n")

    def save(field):
        g.code.extend(b"\xa3" + struct.pack("<I", field))

    g.call(2, 74, name, 0xC0000000, 3, 0, 3 if child else 1, 0x80, 0)
    save(handle)
    g.require(b"\x83\xf8\xff\x0f\x95\xc0\x3c\x01", 1)
    if child:
        g.call(2, 475, (handle,), 2, 0, 2, 0)
        g.result(0, 2)
        g.call(2, 300)
        g.result(33, 3)
        g.call(2, 618, (handle,), 2, 0, 0)
        g.result(2, 4)
        g.call(2, 535, (handle,), output, 1, actual, 0)
        g.result(0, 5)
        g.call(2, 300)
        g.result(33, 6)
        g.word(actual, 0, 7)
        g.call(2, 717, (handle,), data, 1, actual, 0)
        g.result(0, 8)
        g.call(2, 300)
        g.result(33, 9)
        g.call(2, 475, (handle,), 4, 0, 1, 0)
        g.result(1, 10)
        g.call(2, 702, (handle,), 4, 0, 1, 0)
        g.result(1, 11)
        g.call(1, 325, event_name, event)
        g.result(0, 12)
        g.call(1, 328, (event,))
        g.result(0, 13)
        g.call(1, 326, (event,))
        g.result(0, 14)
    else:
        g.call(2, 717, (handle,), data, 5, actual, 0)
        g.result(1, 15)
        g.call(2, 475, (handle,), 2, 0, 2, 0)
        g.result(1, 16)
        g.call(2, 475, (handle,), 3, 0, 2, 0)
        g.result(0, 17)
        g.call(2, 702, (handle,), 2, 0, 1, 0)
        g.result(0, 18)
        g.call(2, 300)
        g.result(158, 19)
        g.call(2, 618, (handle,), 2, 0, 0)
        g.call(2, 535, (handle,), output, 1, actual, 0)
        g.result(1, 20)
        g.word(actual, 1, 21)
        g.call(2, 74, name, 0xC0000000, 3, 0, 3, 0x80, 0)
        save(other)
        g.call(2, 475, (other,), 2, 0, 2, 0)
        g.result(0, 22)
        g.call(2, 44, (other,))
        g.result(1, 23)
        g.call(1, 324, event_name, event, 1, 0)
        g.result(0, 24)
        g.call(1, 282, 1, ready, 7, actual)
        g.result(0, 25)
        g.call(1, 329, (event,), 15000)
        g.result(0, 26)
        g.call(1, 326, (event,))
        g.result(0, 27)
        g.call(2, 702, (handle,), 2, 0, 2, 0)
        g.result(1, 28)
        g.call(2, 475, (handle,), 2, 1, 2, 0)
        g.result(1, 29)  # Beyond EOF, without extending the file.
        g.call(2, 702, (handle,), 2, 1, 2, 0)
        g.result(1, 30)
    g.call(2, 44, (handle,))
    g.result(1, 31)
    g.exit(0)
    return linear_image(g.code, g.fixups, ["DOSCALLS", "PMWINX"], "FILELOCK32", data=g.data)
