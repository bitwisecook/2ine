/* Refresh bridge-owned resolver files while preserving manually configured files. */
#include "emulator/process/internal.h"
#include "emulator/resolver_files.h"
#include "host/network.h"
#include "host/socket.h"
#include <ctype.h>
static const char Managed[] = "# Generated by 2ine: host network configuration\r\n";

static int make_directories(char *path)
{
    for (char *p = path + 1;; p++)
    {
        if (*p != '/' && *p)
            continue;
        char ch = *p;
        *p = 0;
        LxHostFileInfo info;
        LxHostFsError error = lx_host_path_info(path, &info);
        if (error == LX_HOST_FS_MISSING)
        {
            lx_host_path_mkdir(path);
            error = lx_host_path_info(path, &info);
        }
        int ok = error == LX_HOST_FS_OK && info.kind == LX_HOST_FILE_DIRECTORY;
        *p = ch;
        if (!ok)
            return 0;
        if (!ch)
            return 1;
    }
}

static int save_managed(const char *directory, const char *etc, const char *name, const char *text,
                        size_t size)
{
    size_t capacity = strlen(directory) + strlen(etc) + strlen(name) + 64;
    char *guest = malloc(capacity), *temporary = malloc(capacity);
    if (!guest || !temporary)
    {
        free(guest);
        free(temporary);
        return 0;
    }
    snprintf(guest, capacity, "%s\\%s", etc, name);
    uint32 path_error;
    char *path = lxMakeUnixPath(guest, &path_error);
    free(guest);
    if (!path)
    {
        free(temporary);
        return 0;
    }
    size_t old_size = 0;
    LxHostFsError error;
    char *old = lx_host_file_snapshot(path, 1024 * 1024, &old_size, &error);
    if (old)
    {
        int managed = old_size >= sizeof Managed - 1 && !memcmp(old, Managed, sizeof Managed - 1);
        free(old);
        if (!managed)
        {
            free(path);
            free(temporary);
            return 1;
        }
    }
    else if (error != LX_HOST_FS_MISSING)
    {
        free(path);
        free(temporary);
        return 0;
    }
    uint32 process, parent;
    lx_host_process_ids(&process, &parent);
    (void)parent;
    LxHostFile *file = NULL;
    for (unsigned attempt = 0; attempt < 16 && !file; attempt++)
    {
        snprintf(temporary, capacity, "%s/.%s.2ine-%u-%u", directory, name, process, attempt);
        file = lx_host_file_open(temporary,
                                 LX_HOST_FILE_WRITE | LX_HOST_FILE_CREATE | LX_HOST_FILE_EXCLUSIVE |
                                     LX_HOST_FILE_NOINHERIT,
                                 0, &error);
    }
    int ok = file != NULL;
    size_t offset = 0;
    while (ok && offset < size)
    {
        size_t written;
        ok = lx_host_file_write(file, text + offset, size - offset, &written) == LX_HOST_FS_OK &&
             written;
        if (ok)
            offset += written;
    }
    if (file)
        lx_host_file_close(file);
    if (ok)
        ok = lx_host_path_move(temporary, path) == LX_HOST_FS_OK;
    if (!ok && file)
        lx_host_path_remove(temporary, 0);
    free(path);
    free(temporary);
    return ok;
}

static int domain_token(const char *value)
{
    size_t n = strlen(value);
    if (!n || n > 253)
        return 0;
    for (const unsigned char *p = (const unsigned char *)value; *p; p++)
        if (!isalnum(*p) && *p != '-' && *p != '.' && *p != '_')
            return 0;
    return 1;
}

void lxPrepareNetworkConfiguration(void)
{
    const char *etc = getenv("ETC");
    if (!etc || !*etc)
        return;
    uint32 error = 0;
    char *directory = lxMakeUnixPath(etc, &error);
    if (!directory)
        return;
    if (!make_directories(directory))
    {
        free(directory);
        return;
    }
    LxHostNetwork network;
    if (lx_host_network_snapshot(&network))
    {
        free(directory);
        return;
    }
    char text[8192];
    size_t used = (size_t)snprintf(text, sizeof text, "%s", Managed);
    unsigned servers = 0;
    for (size_t i = 0; i < network.dns.server_count && servers < 3; i++)
    {
        if (lx_host_socket_parse_address(network.dns.servers[i]) == UINT32_MAX)
            continue;
        used += (size_t)snprintf(text + used, sizeof text - used, "nameserver %s\r\n",
                                 network.dns.servers[i]);
        servers++;
    }
    if (network.dns.search_count && domain_token(network.dns.search[0]))
        used += (size_t)snprintf(text + used, sizeof text - used, "domain %s\r\n",
                                 network.dns.search[0]);
    unsigned count = 0;
    for (size_t i = 0; i < network.dns.search_count && count < 6; i++)
        if (domain_token(network.dns.search[i]))
        {
            used += (size_t)snprintf(text + used, sizeof text - used, "%s%s",
                                     count ? " " : "search ", network.dns.search[i]);
            count++;
        }
    if (count)
        used += (size_t)snprintf(text + used, sizeof text - used, "\r\n");
    int ok = save_managed(directory, etc, "RESOLV2", text, used);
    ok &= save_managed(directory, etc, "RESOLV", text, used);
    size_t size = 0;
    LxHostFsError fs_error;
    char *hosts = lx_host_file_snapshot("/etc/hosts", 1024 * 1024, &size, &fs_error);
    if (hosts)
    {
        char *owned = malloc(sizeof Managed - 1 + size);
        if (owned)
        {
            memcpy(owned, Managed, sizeof Managed - 1);
            memcpy(owned + sizeof Managed - 1, hosts, size);
            ok &= save_managed(directory, etc, "HOSTS", owned, sizeof Managed - 1 + size);
            free(owned);
        }
        free(hosts);
    }
    if (!ok && GProcessState.trace_native)
        fprintf(stderr, "2ine: could not refresh managed resolver files in %s\n", etc);
    lx_host_network_destroy(&network);
    free(directory);
}
